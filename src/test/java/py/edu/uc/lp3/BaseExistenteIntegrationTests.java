package py.edu.uc.lp3;

import java.sql.DriverManager;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.context.ApplicationContextInitializer;
import org.springframework.context.ConfigurableApplicationContext;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ContextConfiguration;
import py.edu.uc.lp3.domain.EntidadRegistro;
import py.edu.uc.lp3.domain.TipoEntidad;
import py.edu.uc.lp3.repository.EntidadRepository;
import py.edu.uc.lp3.rest.dto.EntidadDatos;
import py.edu.uc.lp3.rest.dto.ExplosionDatos;
import py.edu.uc.lp3.service.EntidadService;
import py.edu.uc.lp3.service.ExplosionService;

import static org.assertj.core.api.Assertions.assertThat;

/** Comprueba ddl-auto=update sobre una base antigua aislada, nunca sobre ./data. */
@SpringBootTest(properties = {
        "spring.datasource.url=jdbc:h2:mem:base-antigua-test;DB_CLOSE_DELAY=-1",
        "spring.jpa.hibernate.ddl-auto=update"
})
@ContextConfiguration(initializers = BaseExistenteIntegrationTests.BaseAntigua.class)
@DirtiesContext
class BaseExistenteIntegrationTests {

    static class BaseAntigua implements ApplicationContextInitializer<ConfigurableApplicationContext> {
        @Override
        public void initialize(ConfigurableApplicationContext context) {
            try (var conexion = DriverManager.getConnection(
                    "jdbc:h2:mem:base-antigua-test;DB_CLOSE_DELAY=-1", "sa", "");
                 var sql = conexion.createStatement()) {
                sql.execute("""
                        create table entidades (
                          id bigint generated by default as identity primary key,
                          nombre varchar(255) not null, vida integer not null,
                          dano_base integer not null, velocidad_movimiento double precision not null,
                          ancho double precision not null, alto double precision not null,
                          profundidad double precision not null)
                        """);
                sql.execute("""
                        insert into entidades (nombre,vida,dano_base,velocidad_movimiento,ancho,alto,profundidad)
                        values ('Creeper',20,5,0.7,0.6,1.7,0.6), ('Zombie',20,5,0.7,0.6,1.95,0.6)
                        """);
            } catch (Exception e) {
                throw new IllegalStateException("No se pudo preparar la base antigua de prueba", e);
            }
        }
    }

    @Autowired
    private EntidadRepository repository;
    @Autowired
    private EntidadService entidades;
    @Autowired
    private ExplosionService explosiones;

    @Test
    void conservaIdsYVidasYPermiteUbicarLasEntidadesAntiguas() {
        assertThat(repository.count()).isEqualTo(2);
        var creeper = entidades.buscar(1L);
        var zombie = entidades.buscar(2L);
        assertThat(creeper.getTipo()).isEqualTo(TipoEntidad.CREEPER);
        assertThat(zombie.getTipo()).isEqualTo(TipoEntidad.ZOMBIE);
        assertThat(creeper.getPosicion()).isNull();
        assertThat(zombie.getPosicion()).isNull();
        assertThat(creeper.isCargado()).isFalse();
        assertThat(zombie.getVida()).isEqualTo(20);

        entidades.actualizar(1L, datos(creeper, new EntidadDatos.PosicionDatos(0.0, 0.0, 0.0)));
        entidades.actualizar(2L, datos(zombie, new EntidadDatos.PosicionDatos(1.0, 0.0, 0.0)));
        explosiones.simular(new ExplosionDatos(1L));
        assertThat(repository.existsById(1L)).isFalse();
        assertThat(repository.findById(2L).orElseThrow().getVida()).isEqualTo(7);
    }

    private EntidadDatos datos(EntidadRegistro e, EntidadDatos.PosicionDatos posicion) {
        var hitbox = e.getHitbox();
        return new EntidadDatos(e.getNombre(), e.getVida(), e.getDanoBase(), e.getVelocidadMovimiento(),
                new EntidadDatos.HitboxDatos(hitbox.getAncho(), hitbox.getAlto(), hitbox.getProfundidad()),
                e.getSonidos(), e.getDrop(), null, null, posicion);
    }
}
